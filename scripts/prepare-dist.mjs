import fs from "node:fs";
import path from "node:path";

const DIST = path.resolve("dist");
const VERSION = JSON.parse(fs.readFileSync("package.json", "utf8")).version;

function copy(source, target) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.copyFileSync(source, target);
}

function walk(directory, base = directory) {
    return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
        const full = path.join(directory, entry.name);
        if (entry.isDirectory()) return walk(full, base);
        return [path.relative(base, full).split(path.sep).join("/")];
    });
}

if (!fs.existsSync(path.join(DIST, "index.html"))) {
    throw new Error("dist/index.html no existe. Ejecutá vite build antes de prepare-dist.");
}

copy("database/falcon.db", path.join(DIST, "database/falcon.db"));
for (const wasm of ["sql-wasm.wasm", "sql-wasm-browser.wasm"]) {
    copy(path.join("node_modules/sql.js/dist", wasm), path.join(DIST, "node_modules/sql.js/dist", wasm));
}

const precache = walk(DIST)
    .filter(file => file !== "sw.js")
    .filter(file => !file.endsWith(".map"))
    .map(file => `./${file}`)
    .sort();

const cacheName = `falcon-${VERSION}-${Date.now().toString(36)}`;

const worker = `/* Generated by scripts/prepare-dist.mjs. Do not edit dist/sw.js. */
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", event => {
    self.skipWaiting();
    event.waitUntil(
        caches.open(CACHE).then(cache =>
            Promise.all(PRECACHE.map(url =>
                cache.add(url).catch(error => console.warn("Precache falló", url, error))
            ))
        )
    );
});

self.addEventListener("activate", event => {
    event.waitUntil(
        caches.keys()
            .then(keys => Promise.all(keys
                .filter(key => key.startsWith("falcon-") && key !== CACHE)
                .map(key => caches.delete(key))
            ))
            .then(() => clients.claim())
    );
});

self.addEventListener("fetch", event => {
    const request = event.request;
    if (request.method !== "GET") return;
    const url = new URL(request.url);
    if (url.origin !== self.location.origin) return;

    if (request.mode === "navigate") {
        event.respondWith(
            fetch(request)
                .then(response => {
                    const copy = response.clone();
                    caches.open(CACHE).then(cache => cache.put("./index.html", copy)).catch(() => {});
                    return response;
                })
                .catch(() => caches.match("./index.html"))
        );
        return;
    }

    if (url.pathname.endsWith("/database/falcon.db")) {
        event.respondWith(
            fetch(request)
                .then(response => {
                    const copy = response.clone();
                    caches.open(CACHE).then(cache => cache.put(request, copy)).catch(() => {});
                    return response;
                })
                .catch(() => caches.match(request))
        );
        return;
    }

    event.respondWith(
        caches.match(request).then(cached => {
            if (cached) return cached;
            return fetch(request).then(response => {
                if (response.ok) {
                    const copy = response.clone();
                    caches.open(CACHE).then(cache => cache.put(request, copy)).catch(() => {});
                }
                return response;
            });
        })
    );
});
`;

fs.writeFileSync(path.join(DIST, "sw.js"), worker, "utf8");
console.log(`Service worker ${cacheName}: ${precache.length} archivos precargados.`);
